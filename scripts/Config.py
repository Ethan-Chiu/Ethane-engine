"""Versions, download locations and per-platform settings used by Setup.py."""

import platform
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # repository root

SYSTEM = platform.system()  # "Darwin" or "Windows"; others aren't supported yet
IS_MAC = SYSTEM == "Darwin"
IS_WINDOWS = SYSTEM == "Windows"

DOWNLOAD_DIR = ROOT / "vendor" / "downloads"  # gitignored


class Premake:
    version = "5.0.0-beta7"
    install_dir = ROOT / "vendor" / "premake" / "bin"
    executable = install_dir / ("premake5.exe" if IS_WINDOWS else "premake5")
    _base = f"https://github.com/premake/premake-core/releases/download/v{version}/premake-{version}"
    url = f"{_base}-windows.zip" if IS_WINDOWS else f"{_base}-macosx.tar.gz"
    # Generated by default; override with --action. gmake (the old gmake2) is handy for clangd via `bear -- make`.
    actions = ["vs2022", "gmake"] if IS_WINDOWS else ["xcode4", "gmake"]


class Vulkan:
    version = "1.4.309.0"  # the version the engine is developed and tested against
    # Where the LunarG installer puts SDKs by default: <root>/<version>[/macOS]
    default_root = Path.home() / "VulkanSDK" if IS_MAC else Path("C:/VulkanSDK")
    if IS_WINDOWS:
        url = f"https://sdk.lunarg.com/sdk/download/{version}/windows/VulkanSDK-{version}-Installer.exe"
    else:
        url = f"https://sdk.lunarg.com/sdk/download/{version}/mac/vulkansdk-macos-{version}.zip"


class CMake:
    version = "4.2.1"
    if IS_WINDOWS:
        url = f"https://github.com/Kitware/CMake/releases/download/v{version}/cmake-{version}-windows-x86_64.msi"
    else:
        url = f"https://github.com/Kitware/CMake/releases/download/v{version}/cmake-{version}-macos-universal.dmg"


class Deps:
    """Third-party libraries built from their submodules with CMake (see Dependencies.lua)."""

    vendor_dir = ROOT / "EthaneEngine" / "vendor"
    build_dir = vendor_dir / "build"  # build trees in cmake/, installed libraries in <Config>/

    # macOS links the Release libraries in every configuration (no runtime library to match);
    # MSVC needs Debug libraries for Debug builds (/MDd vs /MD)
    configs = ["Debug", "Release"] if IS_WINDOWS else ["Release"]

    common_args = [
        # premake builds macOS for arm64; 11.0 is the lowest target arm64 supports, and matching it
        # avoids "built for newer macOS version" link warnings
        "-DCMAKE_OSX_ARCHITECTURES=arm64",
        "-DCMAKE_OSX_DEPLOYMENT_TARGET=11.0",
    ] if IS_MAC else []

    libraries = {
        "assimp": [
            # Windows: a DLL (copied next to the editor by premake); macOS: static, using the system zlib
            f"-DBUILD_SHARED_LIBS={'ON' if IS_WINDOWS else 'OFF'}",
            "-DASSIMP_BUILD_TESTS=OFF",
            "-DASSIMP_BUILD_ASSIMP_TOOLS=OFF",
            "-DASSIMP_BUILD_SAMPLES=OFF",
            "-DASSIMP_WARNINGS_AS_ERRORS=OFF",
            "-DASSIMP_INSTALL_PDB=OFF",
        ],
        "yaml-cpp": [
            "-DYAML_BUILD_SHARED_LIBS=OFF",
            "-DYAML_CPP_BUILD_TESTS=OFF",
            "-DYAML_CPP_BUILD_TOOLS=OFF",
            "-DYAML_CPP_FORMAT_SOURCE=OFF",
        ],
    }
